                        <ul class="sublista">
                            <li>Conserva intactos el salvado y el germen del cereal.</li>
                            <li>Aporte significativamente mayor de fibra dietética, minerales y vitaminas.</li>
                        </ul>

                        <p><strong>Harina refinada (Endospermo)</strong></p>
                        <ul class="sublista">
                            <li>Sometida a un proceso de molienda que descarta las capas externas.</li>
                            <li>Aporta energía de forma más rápida, pero con menor densidad mineral.</li>
                        </ul>
