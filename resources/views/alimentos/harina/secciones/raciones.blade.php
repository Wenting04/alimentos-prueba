<div class="ration-card">
    <h3>Conservación y propiedades críticas</h3>

    <ul class="ration-list">
        <li>
            <strong>Control de humedad ambiental:</strong>
            Debe almacenarse obligatoriamente en lugares secos y protegidos de la humedad exterior. Una humedad superior al 15% rompe la estabilidad del producto y favorece el crecimiento de mohos.
        </li>

        <li>
            <strong>Impacto de la granulometría:</strong>
            El tamaño de la partícula o granulometría es una variable física crítica que influye directamente en la tasa de absorción de agua y en la textura final de la masa.
            <img src="{{ asset('img/harina/granulometria.jpg') }}" alt="Granulometría de la harina">
        </li>
    </ul>
