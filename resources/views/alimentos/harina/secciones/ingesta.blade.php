<div class="content-card">
    <h3>Aplicaciones dietéticas de las harinas</h3>

    <p>
        Las harinas aportan energía a base de carbohidratos complejos, fibra y micronutrientes esenciales. Su correcta selección es clave para optimizar el rendimiento y el control metabólico en dietas equilibradas.
    </p>

    <ul class="simple-list">
        <li><strong>Control metabólico:</strong> Las harinas de bajo índice glucémico ayudan a regular y controlar los niveles de glucosa en sangre.</li>
        <li><strong>Salud intestinal y celiaquía:</strong> Las harinas sin gluten están estrictamente indicadas para personas con enfermedad celíaca o sensibilidad.</li>
        <li><strong>Nutrición deportiva:</strong> Las harinas ricas en carbohidratos complejos son de gran utilidad para la reposición de glucógeno y energía sostenida.</li>
    </ul>
</div>

<div class="content-card">
    <h3>Tipos especiales de harinas y propiedades</h3>

    <div class="recommendation-grid">
        <div class="recommendation-item">
            <strong>Harinas de legumbres</strong>
            <p>
                Destacan por ser muy ricas en proteína vegetal y fibra, ideales para aumentar el valor proteico.
            </p>
        </div>

        <div class="recommendation-item">
            <strong>Harinas de frutos secos</strong>
            <p>
                Contienen grasas saludables, aportan densidad calórica de calidad y poseen un bajo índice glucémico.
            </p>
        </div>

        <div class="recommendation-item">
            <strong>Harinas de bajo índice glucémico</strong>
            <p>
                Recomendadas para el control de la glucosa y para evitar picos de insulina en dietas de control de peso.
            </p>
        </div>

        <div class="recommendation-item">
            <strong>Harinas sin gluten</strong>
            <p>
                Alternativas seguras basadas en cereales como el arroz, maíz o pseudocereales para el manejo de la celiaquía.
            </p>
        </div>

        <div class="recommendation-item">
            <strong>Harinas ricas en carbohidratos complejos</strong>
            <p>
                Combustible de absorción lenta, indicadas especialmente en comidas previas a entrenamientos deportivos de resistencia.
            </p>
        </div>

        <div class="recommendation-item">
            <strong>Harinas integrales o de grano entero</strong>
            <p>
                Conservan el salvado y el germen, maximizando el aporte de fibra dietética, vitaminas y minerales.
            </p>
        </div>
    </div>
</div>