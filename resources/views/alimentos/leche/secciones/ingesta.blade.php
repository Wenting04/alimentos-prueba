<!-- RECOMENDACIONES -->
<div class="content-card">
    <h3>Recomendaciones según grupo y patología</h3>

    <div class="recommendation-grid">
        <div class="recommendation-item">
            <strong>Niños (2–9 años)</strong>
            <p>
            2–3 raciones/día. Leche entera a partir del primer año.
            </p>
        </div>

        <div class="recommendation-item">
            <strong>Adultos</strong>
            <p>2–3 raciones/día. Preferiblemente semidesnatada.</p>
        </div>

        <div class="recommendation-item">
            <strong>Embarazadas</strong>
            <p>4–5 raciones/día. Enriquecida en calcio.</p>
        </div>

        <div class="recommendation-item">
            <strong>Personas mayores</strong>
            <p>2–3 raciones/día. Preferiblemente desnatada.</p>
        </div>

        <div class="recommendation-item">
            <strong>Enfermedades cardiovasculares / Colesterol</strong>
            <p>Leche desnatada.</p>
        </div>

        <div class="recommendation-item">
            <strong>Sobrepeso / Obesidad</strong>
            <p>Semidesnatada o desnatada.</p>
        </div>

        <div class="recommendation-item">
            <strong>Deportistas</strong>
            <p>Leche entera como buena fuente proteica.</p>
        </div>

        <div class="recommendation-item">
            <strong>Intolerancia a la lactosa</strong>
            <p>Leche sin lactosa.</p>
        </div>
    </div>
</div>